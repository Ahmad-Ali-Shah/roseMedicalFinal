export function localizeLegalDocument(document: LegalDocumentRecord): LegalDocumentRecord {
  const translations = document.slug === "privacy" ? PRIVACY_AR : TERMS_AR;
  return {
    ...document,
    title: document.slug === "privacy" ? "سياسة الخصوصية" : "شروط استخدام الموقع",
    breadcrumbLabel: document.slug === "privacy" ? "سياسة الخصوصية" : "شروط الاستخدام",
    updated: "6 أغسطس 2026",
    introduction: document.slug === "privacy"
      ? "توضح هذه السياسة كيفية التعامل مع المعلومات المقدمة عبر موقع روزا ميديكال لأغراض دعم الكتالوج ورسائل التواصل وطلبات عروض الأسعار."
      : "تنظم هذه الشروط استخدام صفحات الكتالوج والتواصل والاستفسار وطلب عرض السعر في موقع روزا ميديكال.",
    sections: document.sections.map((section, index) => ({
      ...section,
      title: translations[index]?.[0] ?? section.title,
      body: translations[index]?.[1] ?? section.body
    }))
  };
}
